// FOR LOOP
let i;

for(i = 1 ; i <=5 ; i++){
    console.log("*");
}  

console.log("\n");

// WHILE LOOP

let j = 1;

while(j <= 5){
    console.log("*");
    j = j + 1;
}

console.log("\n");

// DO-WHILE LOOP
let k = 1;
let result = "";
do{
    result += "*";
    k++;
}
while(k <= 10);

console.log(result);

